#!/usr/bin/env node
/**
 * Put the /insights/ dynamic routes in place, or take them away.
 *
 * ## Why this exists at all
 *
 * `output: "export"` refuses to build a dynamic route that yields zero paths:
 *
 *     if (config.output === 'export' && isDynamic && !hasGenerateStaticParams)
 *       throw new Error(`Page "${page}" is missing "generateStaticParams()" …`)
 *                                            — next/dist/build/index.js
 *
 * There is no flag that softens it, and the message names a function that is
 * present and returned an empty array, so it sends you hunting in a file with no
 * bug in it. Phase 4 ships with **zero** CMS articles by design — the whole
 * acceptance test is that `out/` is unchanged — so a committed
 * `src/app/insights/[category]/[slug]/page.tsx` would mean a repo that cannot
 * build until somebody publishes something.
 *
 * So the route's *existence* follows the content. The route bodies are ordinary
 * reviewed, typechecked, linted source under src/lib/insight-routes/; this
 * script copies them into src/app/ when they have something to render and
 * removes them when they do not. Both copies are gitignored: D1 is the source of
 * truth for whether they should exist, and a committed copy would be a second
 * one that can disagree.
 *
 * ## What decides
 *
 *   [category]/[slug]  — needed when the CMS has at least one article (drafts
 *                        included: a draft is reviewable at its real URL).
 *   [category]         — needed when at least one category with a PUBLISHED
 *                        article has no literal folder in the repo. Drafts do
 *                        not open a category index; an index over nothing is
 *                        the thin content Search Console flags.
 *
 * ## Failure policy
 *
 * Hard, matching src/lib/insights.ts and the news pipeline before it. An
 * unreachable CMS must fail the build rather than quietly removing the routes —
 * that would delete every article path from the export, and Cloudflare Pages
 * then serves the deleted paths from the edge for up to seven days. `--soft`
 * downgrades it to a warning and is for `npm run dev` only.
 */

import { mkdir, rm, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { insights as authored } from "../src/lib/data/insights.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOFT = process.argv.includes("--soft");

const API =
  process.env.INSIGHTS_API_URL ??
  "https://mvg-news.jason-6bf.workers.dev/api/cms/insights";

/** source under src/lib → destination under src/app */
const ROUTES = [
  {
    name: "[category]/[slug]",
    from: "src/lib/insight-routes/article.tsx",
    to: "src/app/insights/[category]/[slug]/page.tsx",
  },
  {
    name: "[category]",
    from: "src/lib/insight-routes/category.tsx",
    to: "src/app/insights/[category]/page.tsx",
  },
];

const BANNER = `/* GENERATED by scripts/sync-insight-routes.mjs — do not edit, do not commit.
   The reviewable source is {FROM}. Edit that. */
`;

async function main() {
  let items;
  try {
    const res = await fetch(`${API}?b=${Date.now().toString(36)}`, {
      headers: { accept: "application/json" },
    });
    if (!res.ok) throw new Error(`status ${res.status}`);
    const data = await res.json();
    if (!Array.isArray(data?.items)) {
      // The same assertion pull-images.mjs learned the hard way: a 200 with an
      // unexpected body must not be read as "nothing published".
      throw new Error("response has no `items` array");
    }
    items = data.items;
  } catch (err) {
    const msg = `[insight-routes] could not read the CMS index from ${API} — ${err}`;
    if (SOFT) {
      console.warn(`${msg} — leaving the routes as they are (dev only).`);
      return;
    }
    console.error(
      `${msg}\n\nThe build is stopping on purpose. Carrying on would remove every ` +
        `/insights/ article page from the export, and Pages serves deleted paths ` +
        `from the edge for up to seven days afterwards. Check the mvg-news Worker ` +
        `is up, then rebuild.`,
    );
    process.exit(1);
  }

  const published = items.filter((it) => !it.draft);
  const authoredCategories = new Set(authored.map((a) => a.category));
  const needsCategoryRoute = published.some(
    (it) => !authoredCategories.has(it.category),
  );

  const want = {
    "[category]/[slug]": items.length > 0,
    "[category]": needsCategoryRoute,
  };

  for (const route of ROUTES) {
    const dest = path.join(ROOT, route.to);
    if (want[route.name]) {
      await mkdir(path.dirname(dest), { recursive: true });
      const src = await readFile(path.join(ROOT, route.from), "utf8");
      await writeFile(dest, BANNER.replace("{FROM}", route.from) + src);
      console.log(`[insight-routes] ${route.name} → on`);
    } else if (existsSync(dest)) {
      await rm(dest);
      console.log(`[insight-routes] ${route.name} → off (removed)`);
    }
  }

  // Leave no empty directories behind: Next treats a directory under app/ with
  // no page as inert, but an empty `[category]` folder in a working tree is a
  // thing somebody will try to explain later.
  const catDir = path.join(ROOT, "src/app/insights/[category]");
  if (!want["[category]"] && !want["[category]/[slug]"] && existsSync(catDir)) {
    await rm(catDir, { recursive: true, force: true });
  }

  console.log(
    `[insight-routes] ${items.length} CMS article(s), ${published.length} published.`,
  );
}
await main();
